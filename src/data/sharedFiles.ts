  "",
  "## What is Microservices?",
  "",
  "Microservices is an architectural style where an application is built as a collection of small, independent services. Each service:",
  "",
  "- Runs in its own process",
  "- Has its own database",
  "- Communicates via REST APIs",
  "- Can be deployed independently",
  "",
  "## Why Microservices?",
  "",
  "### Advantages",
  "- Independent development and deployment",
  "- Technology flexibility per service",
  "- Fault isolation",
  "- Scalability",
  "- Easier maintenance",
  "",
  "### Disadvantages",
  "- Network communication overhead",
  "- Data consistency challenges",
  "- More complex infrastructure",
  "- Service discovery needed",
  "",
  "## This Project",
  "",
  "### Menu Service (Port 8081)",
  "- Manages food items and categories",
  "- Independent database: food_menu_db",
  "- Provides prices to Order Service",
  "",
  "### Order Service (Port 8082)",
  "- Manages customer orders",
  "- Independent database: food_order_db",
  "- Calls Menu Service for price verification",
  "- Calls Delivery Service when order confirmed",
  "",
  "### Delivery Service (Port 8083)",
  "- Manages delivery tracking",
  "- Independent database: food_delivery_db",
  "- Called by Order Service",
  "",
  "## Communication Flow",
  "",
  "1. Client creates order via Order Service",
  "2. Order Service calls Menu Service to verify food and get prices",
  "3. Order Service calculates total and saves order",
  "4. When order is CONFIRMED, Order Service calls Delivery Service",
  "5. Delivery Service creates delivery record",
  "",
  "## MicroProfile Health",
  "",
